if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--batch", action="store_true",
                     help="Run every trace in --traces-dir instead of a single file")
    ap.add_argument("trace_or_dir", help="A single trace .json path, or (with --batch) a directory of them")
    ap.add_argument("--out-dir", default="results/alerts", help="Batch mode: where to write the .md alerts")
    ap.add_argument("--gt-dir", default=None, help="Optional: ground_truth_batch*.json directory, for real company names/dates")
    ap.add_argument("--provider", default=None, choices=["ollama", "groq"],
                     help="If given, calls llm_setup.build_llm() to write real prose. Omit to just print the raw facts (no LLM call).")
    ap.add_argument("--model", default=None, help="Optional model override, passed through to build_llm()")
    args = ap.parse_args()

    llm = None
    if args.provider:
        from llm_setup import build_llm
        llm = build_llm(provider=args.provider, model=args.model)

    if args.batch:
        generate_all_alerts(args.trace_or_dir, args.out_dir, llm=llm, gt_dir=args.gt_dir)
    else:
        import json

        with open(args.trace_or_dir, encoding="utf-8") as f:
            trace = json.load(f)
        event_id = args.trace_or_dir.rsplit("/", 1)[-1].removesuffix(".json")
        company_name, event_date = _company_and_date_for_event(event_id, args.gt_dir)
        result = generate_alert(event_id, company_name, event_date, trace, llm=llm)
        print(result["alert_text"])